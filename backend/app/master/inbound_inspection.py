"""검수 사실의 출처가 **아직 없다**는 것을 배선에 적는 자리.

물류가 `#329` 로 입고 실행을 올리면서 `InspectionProvider` 를 **일부러 안 만들었다.**
그 Protocol docstring 의 문장을 그대로 옮긴다.

    자동 검수 규칙(합격률·등급별 판정·수량 배분)을 정한 문서도 코드도 씨앗 데이터도
    없다. 여기에 기본 구현을 놓으면 **아무도 정한 적 없는 비율이 곧 업무 사실이 되어**
    원가·폐기·판매 판단으로 흘러간다.

★ 그리고 길을 하나 열어 뒀다 — *"항상 `None` 을 내는 provider 는 정당한 배선이다."*
  이 파일이 그 배선이다.

---

🔴 **왜 배선을 안 하는 것보다 이것이 나은가.** 둘은 다른 사실이다.

```text
배선을 안 한다      "입고 실행 미등록"        ← 배선 문제. **사실이 아니다** — 구현은 섰다
Null provider       "검수 사실을 모른다"      ← 그날의 사실. 화면에 매일 보인다
```

★ *"안 부른 것과 못 부른 것은 다르다"* 와 같은 자리다. 지금 도착 예정 `2026-01-07` 이
  `02-06` 까지 `in_transit` 에 **묻혀서 안 보인다.** 배선을 안 하면 계속 안 보이고,
  이걸 붙이면 `BLOCKED / INSPECTION_FACT_UNAVAILABLE` 로 **매일 보인다.**

⚠️ **매일 빨간불이 뜨는 것이 이 배선의 목적이다.** 조용해지면 그때가 이상한 것이다.

---

🔴 **이 파일은 지워질 파일이다.** `app/master/finance_cancellation.py` 와 같은 자리다 —
   검수 사실의 주인이 정해져 자기 provider 를 올리면 **이 파일을 지우고 `app/main.py`
   의 한 줄만 바꾸면 된다.**

⚠️ **검수 규칙의 주인이 누구인지는 마스터가 안 정한다.** 물류·매입 어느 쪽인지(혹은
  제3의 자리인지)는 별건이고, 여기서 고르면 *"아무도 정한 적 없는 비율"* 을 막으려던
  물류의 판단을 마스터가 우회하는 셈이 된다.

★ **물류 타입을 임포트하지 않는다.** 구조적 타이핑이라 필요 없고, 마스터가 물류
  내부 타입(`DueInbound` · `PurchaseDetail`)에 매이면 물류가 그것을 바꾸는 날 배선이
  깨진다. 값을 안 보고 항상 `None` 을 내는 구현에는 그 타입이 필요 없다.
"""

from __future__ import annotations

from datetime import date
from typing import Any


class NoInspectionSource:
    """검수 사실을 **모른다**고 답한다. 언제나.

    🔴 **`None` 은 실패가 아니라 부재다** (물류 `InspectionProvider` 참조). 예외를
       올리면 마스터가 롤백하고 그날 입고를 통째로 `FAILED` 로 만든다 — 그것은
       *"검수 원천이 없다"* 가 아니라 *"실행이 깨졌다"* 다.

    ⚠️ **`provide` 는 잠금을 쥔 채 불린다** (도착 전역 advisory + 그날 fixture 행
      `FOR UPDATE`). 그래서 이 구현은 **아무것도 하지 않는다** — 조회도 대기도 없다.
      나중에 진짜 provider 가 들어올 때 그 제약을 지켜야 하는 자리가 여기다.
    """

    def provide(
        self,
        *,
        as_of: date,
        inbound: Any,
        purchase_detail: Any,
    ) -> None:
        """언제나 `None`. **인자를 보지 않는다.**

        ★ 값에 따라 답이 갈리면 그것은 이미 검수 정책이다. 이 자리는 정책이 **없다**는
          것을 적는 자리이므로, 무엇이 들어와도 같은 답이어야 한다.
        """
        return None
